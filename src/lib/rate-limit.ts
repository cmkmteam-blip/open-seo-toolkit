const hits = new Map<string, number[]>();

/**
 * Sliding-window limiter, in memory per server instance. Good enough to stop casual abuse of a
 * self-hosted deployment; use a shared store (e.g. Redis) if you need exact limits across instances.
 */
export function rateLimit(key: string, max: number, windowMs: number, now = Date.now()): boolean {
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  if (recent.length >= max) {
    hits.set(key, recent);
    return false;
  }
  recent.push(now);
  hits.set(key, recent);
  if (hits.size > 10_000) {
    for (const [k, v] of hits) if (v.every((t) => now - t >= windowMs)) hits.delete(k);
  }
  return true;
}
